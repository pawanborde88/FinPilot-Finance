using FinPilot.Application;
using FinPilot.Infrastructure;
using FinPilot.Infrastructure.Persistence;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.EntityFrameworkCore.Storage;

var builder = WebApplication.CreateBuilder(args);

// Add Clean Architecture layers
builder.Services.AddApplicationServices();
builder.Services.AddInfrastructureServices(builder.Configuration);

// Add Controller services
builder.Services.AddControllers();

// Configure Swagger / OpenAPI
builder.Services.AddEndpointsApiExplorer();
builder.Services.AddSwaggerGen();

var app = builder.Build();

// Ensure Database Schema is up to date on startup
using (var scope = app.Services.CreateScope())
{
    var services = scope.ServiceProvider;
    var logger = services.GetRequiredService<ILogger<Program>>();
    try
    {
        var dbContext = services.GetRequiredService<ApplicationDbContext>();
        if (dbContext.Database.IsNpgsql())
        {
            logger.LogInformation("Applying PostgreSQL database schema initialization in Supabase...");

            try
            {
                await dbContext.Database.ExecuteSqlRawAsync(@"
                    DO $$
                    BEGIN
                        IF EXISTS (
                            SELECT 1 FROM information_schema.columns 
                            WHERE table_name = 'Organizations' AND column_name = 'Id' AND data_type = 'integer'
                        ) THEN
                            DROP TABLE IF EXISTS ""Organizations"";
                        END IF;
                    END $$;

                    CREATE TABLE IF NOT EXISTS ""Organizations"" (
                        ""Id"" uuid NOT NULL,
                        ""Name"" character varying(200) NOT NULL,
                        ""Slug"" character varying(100) NOT NULL,
                        ""IsActive"" boolean NOT NULL,
                        ""CreatedAtUtc"" timestamp with time zone NOT NULL,
                        CONSTRAINT ""PK_Organizations"" PRIMARY KEY (""Id"")
                    );

                    CREATE UNIQUE INDEX IF NOT EXISTS ""IX_Organizations_Slug"" ON ""Organizations"" (""Slug"");

                    CREATE TABLE IF NOT EXISTS ""Transactions"" (
                        ""Id"" integer GENERATED BY DEFAULT AS IDENTITY,
                        ""Title"" character varying(200) NOT NULL,
                        ""Description"" character varying(1000),
                        ""Amount"" numeric(18,2) NOT NULL,
                        ""Type"" character varying(20) NOT NULL,
                        ""Category"" character varying(100) NOT NULL,
                        ""TransactionDate"" timestamp with time zone NOT NULL,
                        ""CreatedAtUtc"" timestamp with time zone NOT NULL,
                        ""UpdatedAtUtc"" timestamp with time zone,
                        CONSTRAINT ""PK_Transactions"" PRIMARY KEY (""Id"")
                    );

                    CREATE TABLE IF NOT EXISTS ""__EFMigrationsHistory"" (
                        ""MigrationId"" character varying(150) NOT NULL,
                        ""ProductVersion"" character varying(32) NOT NULL,
                        CONSTRAINT ""PK___EFMigrationsHistory"" PRIMARY KEY (""MigrationId"")
                    );

                    INSERT INTO ""__EFMigrationsHistory"" (""MigrationId"", ""ProductVersion"")
                    VALUES ('20261021123729_InitialPostgreSqlCreate', '10.0.10')
                    ON CONFLICT (""MigrationId"") DO NOTHING;
                ");
                logger.LogInformation("PostgreSQL schema successfully ensured.");
            }
            catch (Exception ex)
            {
                logger.LogError(ex, "An error occurred during PostgreSQL schema initialization.");
            }
        }
        else if (dbContext.Database.IsSqlServer())
        {
            logger.LogInformation("Applying SQL Server database migrations...");
            await dbContext.Database.MigrateAsync();
        }
    }
    catch (Exception ex)
    {
        logger.LogError(ex, "An error occurred while initializing the database.");
    }
}

// Enable Swagger in Development and Production (e.g. Render)
app.UseSwagger();
app.UseSwaggerUI(options =>
{
    options.SwaggerEndpoint("/swagger/v1/swagger.json", "FinPilot API v1");
    options.RoutePrefix = "swagger";
});

// Redirect root to Swagger
app.MapGet("/", () => Results.Redirect("/swagger"));

app.UseHttpsRedirection();

app.UseAuthorization();

app.MapControllers();

app.Run();
